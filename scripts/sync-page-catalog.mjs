import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadPageManifest } from './lib/page-content.mjs';

const manifest = loadPageManifest();
const routes = new Set(),
  names = new Set();
for (const entry of manifest) {
  if (routes.has(entry.route) || names.has(entry.exportName))
    throw new Error(`Duplicate route or component: ${entry.route}`);
  if (!/^[A-Z][A-Za-z0-9]*$/.test(entry.exportName))
    throw new Error(`Invalid component name: ${entry.exportName}`);
  for (const file of [entry.content, entry.component]) {
    const resolved = path.resolve(file);
    if (!resolved.startsWith(path.resolve('src/products') + path.sep) || !existsSync(resolved))
      throw new Error(`Missing product-owned file: ${file}`);
  }
  routes.add(entry.route);
  names.add(entry.exportName);
}
function relative(from, to) {
  const value = path
    .relative(path.dirname(from), to)
    .replaceAll('\\', '/')
    .replace(/\.tsx?$/, '');
  return value.startsWith('.') ? value : './' + value;
}
writeFileSync(
  'src/content/catalog.ts',
  '// Generated by npm run content:catalog from page-manifest.json. Edit product content.json files.\nimport type { DocumentPage } from "../shared/content/types";\n' +
    manifest
      .map(
        (entry, i) =>
          `import page${i} from '${relative('src/content/catalog.ts', entry.content)}';`,
      )
      .join('\n') +
    `\nconst pages: DocumentPage[] = [${manifest.map((_, i) => 'page' + i).join(', ')}];\nexport default pages;\n`,
);
writeFileSync(
  'src/content/documentPages.ts',
  '// Generated by npm run content:catalog. Edit product page compositions and slides.\nimport type { ComponentType } from "react";\nimport type { DocumentPageProps } from "../shared/content/types";\n' +
    manifest
      .map(
        (entry) =>
          `import { ${entry.exportName} } from '${relative('src/content/documentPages.ts', entry.component)}';`,
      )
      .join('\n') +
    `\nexport const documentPages: Record<string, ComponentType<DocumentPageProps>> = {\n${manifest.map((entry) => `${JSON.stringify(entry.route)}: ${entry.exportName}`).join(',\n')}\n};\n`,
);
console.log(`Registered ${manifest.length} product-owned document pages.`);
