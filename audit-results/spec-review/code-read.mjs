import fs from 'node:fs';
import path from 'node:path';
const [file,startArg,endArg] = process.argv.slice(2);
const root = path.resolve('data/spec-review-snapshot/code');
const full = path.resolve(root,file);
if (!full.startsWith(root+path.sep)) throw new Error('Outside snapshot');
const lines=fs.readFileSync(full,'utf8').split(/\r?\n/);
const start=Number(startArg||1),end=Math.min(Number(endArg||lines.length),lines.length);
console.log(lines.slice(start-1,end).map((s,i)=>`${file}:${start+i} ${s}`).join('\n'));
fs.appendFileSync('audit-results/spec-review/code-read-log.jsonl',JSON.stringify({file,start,end,total:lines.length,at:new Date().toISOString()})+'\n');
